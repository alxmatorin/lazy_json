package perfs.json.bench;

/**
 * Способ работы с JSON-байтами. {@link #run} — «пришёл документ, выполни операцию»: подготовка
 * (путь, значение, правка) и выполнение целиком внутри, ничего не кэшируется между вызовами,
 * кроме того, что кэширует сама библиотека. Возвращает число для контрольной суммы,
 * чтобы JIT не выбросил работу как мёртвый код.
 */
public interface Strategy {

    String name();

    int run(Op op, byte[] doc, int iteration);
}
